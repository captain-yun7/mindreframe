-- 약관 제7조 환불규정 문구 수정 (2026-08-12, PG 심사 대응)
-- 전자상거래법 제17조: 디지털콘텐츠 청약철회 제한은 "제공이 개시된 경우"에만 가능.
-- "미사용 시 환불 불가"(20260716)는 법 취지와 반대 → 미사용 시 전액 환불 가능으로 수정.
-- terms_html row가 없으면(코드 fallback 사용 중) no-op.

update site_settings
set value = replace(
  value,
  '<li>결제 후 7일 이내, 콘텐츠 미사용 상태일 경우 환불 불가합니다.</li>',
  '<li>결제 후 7일 이내, 콘텐츠 미사용(이용 개시 전) 상태일 경우 전액 환불 가능합니다.</li>
  <li>콘텐츠 이용 개시 후에는 「전자상거래 등에서의 소비자보호에 관한 법률」 제17조에 따라 청약철회가 제한될 수 있습니다.</li>'
)
where key = 'terms_html'
  and value like '%결제 후 7일 이내, 콘텐츠 미사용 상태일 경우 환불 불가합니다.%';
