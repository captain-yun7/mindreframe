-- 약관 제7조에 월 구독(정기결제) 이용기간·환불·해지 기준 추가 (2026-11-13, 토스 정기결제 심사 대응)
-- 기존 100일 이용권 기준(결제 후 7일 이내 미사용 시 전액 환불)과 동일한 기준을 월 구독에 명시.
-- terms_html row가 없으면(코드 fallback 사용 중) no-op.

update site_settings
set value = replace(
  value,
  '<li>구독형 상품의 경우 다음 결제일 전까지 해지 시 이후 결제가 청구되지 않습니다.</li>',
  '<li>월 구독(정기결제) 상품은 결제일로부터 1개월 단위로 이용기간이 제공되며, 매달 같은 날 등록한 카드로 자동 결제됩니다.</li>
  <li>월 구독 결제 후 7일 이내이고 해당 결제 기간에 이용 내역이 없는 경우 전액 환불 가능합니다.</li>
  <li>월 구독은 마이페이지에서 언제든 해지할 수 있으며, 해지 시 다음 결제일부터 요금이 청구되지 않고 이미 결제한 기간은 종료일까지 이용할 수 있습니다.</li>'
)
where key = 'terms_html'
  and value like '%구독형 상품의 경우 다음 결제일 전까지 해지 시 이후 결제가 청구되지 않습니다.%';
